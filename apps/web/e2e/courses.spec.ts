    await expect(d.getByRole('cell', { name: m }), `admin, Import sections: ${m}`).toBeVisible()
  await d.getByLabel('CSV file').setInputFiles(
    csv('sections.csv', head + `CS210,${demoTerm},002,${P.elena.email},new.ta@${slug}.edu,Fri 09:00-10:20 @ Hall C 1\n`),
  )
  await d.getByRole('button', { name: 'Import 1 rows' }).click()
