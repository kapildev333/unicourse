import { expect, test, type Page } from '@playwright/test'
import { api, demoTerm, expectNoSideScroll, H, pageAs, personas, runId, sectionIds, seedDemo } from './helpers'

const slug = `e2e-crs-${runId}`
const P = personas(slug)
const A = `/api/v1/universities/${slug}`

test.beforeAll(() => {
  seedDemo(slug)
})

const csv = (name: string, text: string) => ({ name, mimeType: 'text/csv', buffer: Buffer.from(text) })
const dialogOf = (page: Page, name: string) => page.getByRole('dialog', { name })
const status = (page: Page, text: string) => page.getByRole('status').filter({ hasText: text })
const participants = async (page: Page, code: string) => {
  const ids = await sectionIds(page, slug)
  await page.goto(`/${slug}/sections/${ids[code]}/participants`)
}

test('E-COURSES-01 course create, edit, delete', async ({ browser }) => {
  const page = await pageAs(browser, P.admin.email, slug)
  await page.goto(`/${slug}/courses`)
  await page.getByRole('button', { name: 'New course' }).first().click()
  const d = dialogOf(page, 'New course')
  await d.getByRole('button', { name: 'Create course' }).click()
  await expect(d.getByText('Choose a department.'), 'admin, New course dialog: department error').toBeVisible()
  await expect(d.getByText('Enter a course code of at most 20 characters.'), 'admin, New course dialog: code error').toBeVisible()
  await expect(d.getByText('Enter a title of at most 200 characters.'), 'admin, New course dialog: title error').toBeVisible()
  await d.getByLabel('Department').selectOption({ label: 'MATH · Mathematics' })
  await d.getByLabel('Code').fill('CS101')
  await d.getByLabel('Title').fill('Probability')
  await d.getByRole('button', { name: 'Create course' }).click()
  await expect(d.getByText('A course with this code already exists in this university.'), 'admin, New course dialog: duplicate code').toBeVisible()
  await d.getByLabel('Code').fill('MATH310')
  await d.getByRole('button', { name: 'Create course' }).click()
  await expect(status(page, 'Course “MATH310” created.'), 'admin, Courses: created notice').toBeVisible()
  await expect(page.getByRole('cell', { name: 'MATH310', exact: true }), 'admin, Courses: new row').toBeVisible()
  await page.getByRole('button', { name: 'Edit MATH310' }).click()
  const e = dialogOf(page, 'Edit MATH310')
  await e.getByLabel('Title').fill('Probability Theory')
  await e.getByRole('button', { name: 'Save changes' }).click()
  await expect(status(page, 'Course “MATH310” updated.'), 'admin, Courses: updated notice').toBeVisible()
  await page.getByRole('button', { name: 'Delete MATH310' }).click()
  const x = dialogOf(page, 'Delete MATH310?')
  await expect(x.getByText('This permanently deletes “Probability Theory”. A course that still has sections can\'t be deleted: delete its sections first.'), 'admin, Delete dialog: description').toBeVisible()
  await x.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(status(page, 'Course “MATH310” deleted.'), 'admin, Courses: deleted notice').toBeVisible()
  await page.context().close()
})

