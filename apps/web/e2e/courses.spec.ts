  await expect(amara.getByRole('textbox', { name: 'Add by email' }), 'student, Participants: no add form').toHaveCount(0)
  const en = await amara.request.get(`${A}/sections/${ids['CS101-001']}/enrollments`)
  expect(en.status(), 'student: API refuses the roster').toBe(403)
  await amara.context().close()

  const owen = await pageAs(browser, P.deptAdmin.email, slug)
  await participants(owen, 'CS101-001')
  await expect(owen.getByRole('button', { name: 'Add instructor' }), 'department admin, CS101 participants: Add instructor').toBeVisible()
  await expect(owen.getByRole('button', { name: 'Import roster' }), 'department admin, CS101 participants: Import roster').toBeVisible()
  await participants(owen, 'ECON110-001')
  await expect(owen.getByRole('heading', { name: /^Staff/ }), 'department admin, ECON110 participants: staff').toBeVisible()
  await expect(owen.getByRole('textbox', { name: 'Add by email' }), 'department admin, ECON110 participants: no add form').toHaveCount(0)
  await expect(owen.getByRole('heading', { name: /^Roster/ }), 'department admin, ECON110 participants: no roster').toHaveCount(0)
