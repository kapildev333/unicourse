test('E-CATALOG-07 weekly schedule, Today, view in the URL', async ({ browser }) => {
  const page = await pageAs(browser, P.amara.email, slug)
  await page.goto(`/${slug}/me`)
  const toggle = page.getByRole('group', { name: 'View' }).getByRole('button', { name: 'Schedule' })
  await toggle.click()
  await expect(toggle, 'member, My sections: Schedule pressed').toHaveAttribute('aria-pressed', 'true')
  await expect(page).toHaveURL(/view=schedule/)
  const day = (d: string) => page.getByRole('region', { name: d, exact: true })
  for (const d of ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'])
    await expect(day(d), `member, Schedule: ${d}`).toBeVisible()
  await expect(day('Monday').getByRole('link', { name: /^CS101-001/ }), 'member, Schedule: Monday CS101 time').toContainText('10:00–11:20')
  await expect(day('Monday').getByRole('link', { name: /^CS101-001/ }), 'member, Schedule: Monday CS101 room').toContainText('Hall B 204')
  await expect(day('Monday').getByRole('link', { name: /^MATH201-001/ }), 'member, Schedule: Monday MATH201 time').toContainText('13:00–14:20')
  await expect(day('Tuesday').getByRole('link', { name: /^CS210-001/ }), 'member, Schedule: Tuesday CS210').toBeVisible()
  await expect(page.getByText(/^Clashes with/), 'member, Schedule: no clashes').toHaveCount(0)
  const today = new Date().toLocaleDateString('en-US', { weekday: 'long' })
  const h = day(today).getByRole('heading')
  await expect(h, 'member, Schedule: today is marked').toHaveAttribute('aria-current', 'date')
  await expect(h, 'member, Schedule: today says Today').toContainText('Today')
  await page.reload()
  await expect(day('Monday'), 'member, Schedule: survives reload').toBeVisible()
  await page.context().close()
})

test('E-CATALOG-08 phone agenda and catalog at 390', async ({ browser }) => {
  const page = await pageAs(browser, P.amara.email, slug)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`/${slug}/me?view=schedule`)
  const day = (d: string) => page.getByRole('region', { name: d, exact: true })
  for (const d of ['Monday', 'Tuesday', 'Wednesday', 'Thursday']) await expect(day(d), `member, agenda: ${d}`).toBeVisible()
  for (const d of ['Friday', 'Saturday', 'Sunday']) await expect(day(d), `member, agenda: no ${d}`).toHaveCount(0)
  const links = day('Monday').getByRole('link')
  await expect(links, 'member, agenda: Monday has two meetings').toHaveCount(2)
  await expect(links.nth(0), 'member, agenda: CS101 first').toHaveAccessibleName(/^CS101-001/)
  await expect(links.nth(1), 'member, agenda: MATH201 second').toHaveAccessibleName(/^MATH201-001/)
  await expectNoSideScroll(page, 'member, agenda')
  await page.goto(`/${slug}/catalog`)
  await expect(showing(page, 5), 'member, Catalog: Showing 5 sections').toBeVisible()
  await expectNoSideScroll(page, 'member, Catalog')
  await page.context().close()
})
