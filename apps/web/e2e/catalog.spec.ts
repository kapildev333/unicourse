import { expect, test, type Page } from '@playwright/test'
import { api, createUniversity, demoTerm, expectNoSideScroll, pageAs, personas, runId, seedDemo, signIn, springTerm } from './helpers'

const slug = `e2e-cat-${runId}`
const P = personas(slug)

test.beforeAll(() => {
  seedDemo(slug)
})

const cards = (page: Page, term: string) => page.getByRole('list', { name: `Sections in ${term}` }).getByRole('listitem')
const card = (page: Page, term: string, code: string) => cards(page, term).filter({ hasText: code })
const showing = (page: Page, n: number) => page.getByRole('status').filter({ hasText: `Showing ${n} section${n === 1 ? '' : 's'}` })
const search = (page: Page) => page.getByRole('searchbox', { name: 'Find a course' })

test('E-CATALOG-01 header search from any page', async ({ browser }) => {
  const page = await pageAs(browser, P.amara.email, slug)
  await page.goto(`/${slug}/me`)
  await expect(search(page), 'member, My sections: search box').toBeVisible()
  await page.keyboard.press('/')
  await expect(search(page), 'member, My sections: "/" focuses search').toBeFocused()
  await page.keyboard.type('algebra')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(new RegExp(`/${slug}/catalog\\?q=algebra`))
  await expect(cards(page, demoTerm), 'member, Catalog: one match').toHaveCount(1)
  await expect(card(page, demoTerm, 'MATH201-001'), 'member, Catalog: MATH201-001').toBeVisible()
  await expect(showing(page, 1), 'member, Catalog: Showing 1 section').toBeVisible()
  await expect(search(page), 'member, Catalog: search keeps query').toHaveValue('algebra')
  await page.context().close()
})

test('E-CATALOG-02 department and term filters, Clear filters keeps the term', async ({ browser }) => {
  const page = await pageAs(browser, P.amara.email, slug)
  await page.goto(`/${slug}/catalog`)
  await expect(showing(page, 5), 'member, Catalog: Showing 5 sections').toBeVisible()
  await page.getByLabel('Department').selectOption({ label: 'ECON · Economics' })
  await expect(cards(page, demoTerm), 'member, Catalog: ECON only').toHaveCount(1)
  await expect(card(page, demoTerm, 'ECON110-001'), 'member, Catalog: ECON110-001').toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(showing(page, 5), 'member, Catalog: cleared, Showing 5 sections').toBeVisible()
  await page.getByLabel('Term').selectOption({ label: springTerm })
  await expect(cards(page, springTerm), 'member, Catalog: spring has one section').toHaveCount(1)
  await expect(card(page, springTerm, 'CS101-002'), 'member, Catalog: CS101-002 no meetings').toContainText('No meeting times')
  await page.getByLabel('Department').selectOption({ label: 'BIO · Biology' })
  await expect(page.getByText('No sections match "Biology"'), 'member, Catalog: empty title').toBeVisible()
  await expect(page.getByText('Try another search or department.'), 'member, Catalog: empty hint').toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).last().click()
  await expect(cards(page, springTerm), 'member, Catalog: term kept after clearing').toHaveCount(1)
  await page.context().close()
})

