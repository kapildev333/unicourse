test('E-CATALOG-05 first-use empty states with no terms', async ({ browser }) => {
  const eslug = `e2e-cat0-${runId}`
  const edomain = `cat0-${runId}.edu`
  createUniversity({ name: `Empty ${runId}`, slug: eslug, domain: edomain, adminEmail: `root@${edomain}` })
  const ctx = await browser.newContext()
  const root = await ctx.newPage()
  await signIn(root, `root@${edomain}`, eslug)
  await root.goto(`/${eslug}/me`)
  await expect(root.getByText('No terms yet'), 'admin, My sections: no terms').toBeVisible()
  await expect(root.getByText('Your schedule appears here once your university sets up its terms.'), 'admin, My sections: hint').toBeVisible()
  await expect(root.getByRole('link', { name: 'Set up terms' }), 'admin, My sections: link').toBeVisible()
  await root.goto(`/${eslug}/catalog`)
  await expect(root.getByText('No terms yet'), 'admin, Catalog: no terms').toBeVisible()
  await expect(root.getByText('The catalog appears here once your university sets up its terms.'), 'admin, Catalog: hint').toBeVisible()
  await root.getByRole('link', { name: 'Set up terms' }).click()
  await expect(root).toHaveURL(`/${eslug}/admin/terms`)
  await expect(root.getByRole('heading', { name: 'Terms' }), 'admin, Terms: heading').toBeVisible()
  await root.goto(`/${eslug}/courses/sections`)
  await expect(root.getByRole('button', { name: 'New section' }), 'admin, Sections: New section disabled').toBeDisabled()
  await expect(root.getByText('Add a term first'), 'admin, Sections: add a term').toBeVisible()
  await expect(root.getByText('An administrator creates terms before sections can be added.'), 'admin, Sections: hint').toBeVisible()
  await api(root, 'post', `/api/v1/universities/${eslug}/invitations`, { email: `member@${edomain}`, role: 'member' })

  const mctx = await browser.newContext()
  const member = await mctx.newPage()
  await signIn(member, `member@${edomain}`, eslug)
  for (const path of ['catalog', 'me']) {
    await member.goto(`/${eslug}/${path}`)
    await expect(member.getByText('No terms yet'), `member, ${path}: no terms`).toBeVisible()
    await expect(member.getByRole('link', { name: 'Set up terms' }), `member, ${path}: no setup link`).toHaveCount(0)
  }
  await ctx.close()
  await mctx.close()
})

